-- Support tickets (clients raise them, the team answers) and project progress updates shown to clients.

create table if not exists public.tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_no integer generated by default as identity,
  client_id uuid not null references public.clients(id) on delete cascade,
  project_id uuid references public.projects(id) on delete set null,
  subject text not null check (length(subject) between 3 and 140),
  category text not null default 'support' check (category in ('support', 'change_request', 'new_service', 'billing', 'other')),
  priority text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  status text not null default 'open' check (status in ('open', 'in_progress', 'waiting_client', 'resolved', 'closed')),
  assigned_to uuid references public.profiles(id) on delete set null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);
create unique index if not exists tickets_no_key on public.tickets (ticket_no);
create index if not exists tickets_client_idx on public.tickets (client_id, updated_at desc);
create index if not exists tickets_status_idx on public.tickets (status, updated_at desc);
alter table public.tickets enable row level security;
create policy tickets_read on public.tickets for select using (public.is_staff() or client_id = public.my_client_id());
create policy tickets_insert on public.tickets for insert
  with check ((public.my_role() = 'client' and client_id = public.my_client_id() and created_by = auth.uid()) or public.is_staff());
create policy tickets_update on public.tickets for update
  using (public.is_staff() or client_id = public.my_client_id())
  with check (public.is_staff() or client_id = public.my_client_id());
create policy tickets_admin_delete on public.tickets for delete using (public.is_admin());

-- Clients may only close or reopen their own tickets; everything else is the team's.
create or replace function public.guard_ticket_update()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null or public.is_staff() then
    if new.status in ('resolved', 'closed') and old.status not in ('resolved', 'closed') then new.resolved_at := now(); end if;
    if new.status not in ('resolved', 'closed') then new.resolved_at := null; end if;
    new.updated_at := now();
    return new;
  end if;
  if new.client_id is distinct from old.client_id or new.subject is distinct from old.subject or new.category is distinct from old.category
     or new.priority is distinct from old.priority or new.assigned_to is distinct from old.assigned_to
     or new.project_id is distinct from old.project_id or new.created_by is distinct from old.created_by then
    raise exception 'Clients can only close or reopen their tickets';
  end if;
  if new.status not in ('open', 'closed') then raise exception 'Clients can only close or reopen their tickets'; end if;
  if new.status = 'closed' and old.status <> 'closed' then new.resolved_at := now(); end if;
  if new.status = 'open' then new.resolved_at := null; end if;
  new.updated_at := now();
  return new;
end $$;
revoke execute on function public.guard_ticket_update() from public, anon, authenticated;
create trigger tickets_guard before update on public.tickets for each row execute function public.guard_ticket_update();

create table if not exists public.ticket_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  author_id uuid references public.profiles(id) on delete set null,
  body text not null check (length(body) between 1 and 4000),
  internal boolean not null default false,   -- team-only note, never shown to the client
  created_at timestamptz not null default now()
);
create index if not exists ticket_messages_idx on public.ticket_messages (ticket_id, created_at);
alter table public.ticket_messages enable row level security;
create policy tmsg_read on public.ticket_messages for select
  using (public.is_staff() or (not internal and exists (select 1 from public.tickets t where t.id = ticket_id)));
create policy tmsg_staff_insert on public.ticket_messages for insert with check (public.is_staff() and author_id = auth.uid());
create policy tmsg_client_insert on public.ticket_messages for insert
  with check (public.my_role() = 'client' and author_id = auth.uid() and not internal and exists (select 1 from public.tickets t where t.id = ticket_id));
create policy tmsg_admin_delete on public.ticket_messages for delete using (public.is_admin());

create or replace function public.bump_ticket()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update public.tickets set updated_at = now() where id = new.ticket_id;
  return new;
end $$;
revoke execute on function public.bump_ticket() from public, anon, authenticated;
create trigger ticket_messages_bump after insert on public.ticket_messages for each row execute function public.bump_ticket();

-- ---------- Project progress updates (what the team tells the client as the work moves) ----------
create table if not exists public.project_updates (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  author_id uuid references public.profiles(id) on delete set null,
  body text not null check (length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists project_updates_idx on public.project_updates (project_id, created_at desc);
alter table public.project_updates enable row level security;
-- Whoever can see the project can see its updates (clients only for projects shared with them).
create policy pupd_read on public.project_updates for select using (exists (select 1 from public.projects p where p.id = project_id));
create policy pupd_insert on public.project_updates for insert with check (public.is_staff() and author_id = auth.uid());
create policy pupd_delete on public.project_updates for delete using (author_id = auth.uid() or public.is_lead());
