-- What the branded invoice document needs: an invoice number, the company's own details,
-- and the client's address and tax number.

-- Invoice numbers (existing invoices are numbered automatically).
alter table public.invoices add column if not exists invoice_no integer generated by default as identity;
create unique index if not exists invoices_invoice_no_key on public.invoices (invoice_no);

-- Client details shown under "Billed to".
alter table public.clients add column if not exists address text;
alter table public.clients add column if not exists tax_id text;

-- Anweo's own details, edited by the admin. One row only.
-- Signed-in people can read it because it is printed on every invoice, including the payment details clients need.
create table public.company_settings (
  id int primary key default 1 check (id = 1),
  legal_name text not null default 'Anweo',
  address text,
  email text,
  phone text,
  website text,
  tax_label text not null default 'Tax ID',
  tax_number text,
  payment_details text,
  invoice_note text,
  updated_at timestamptz not null default now()
);
insert into public.company_settings (id) values (1) on conflict (id) do nothing;

alter table public.company_settings enable row level security;
create policy company_read on public.company_settings for select
  using (public.my_role() is not null);
create policy company_admin_write on public.company_settings for all
  using (public.is_admin()) with check (public.is_admin());

create trigger company_settings_touch before update on public.company_settings
  for each row execute function public.touch_updated_at();
