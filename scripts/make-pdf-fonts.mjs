// Packs the brand fonts into src/lib/pdf-fonts.ts so the invoice PDF works on any server
// without reading font files from disk. Run once: node scripts/make-pdf-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";
const f = (pkg, file) => readFileSync(`node_modules/@fontsource/${pkg}/files/${file}`).toString("base64");
const fonts = {
  interTight400: f("inter-tight", "inter-tight-latin-400-normal.woff"),
  interTight600: f("inter-tight", "inter-tight-latin-600-normal.woff"),
  interTight700: f("inter-tight", "inter-tight-latin-700-normal.woff"),
  mono400: f("jetbrains-mono", "jetbrains-mono-latin-400-normal.woff"),
  mono500: f("jetbrains-mono", "jetbrains-mono-latin-500-normal.woff"),
};
const body = Object.entries(fonts).map(([k, v]) => `  ${k}: "data:font/woff;base64,${v}",`).join("\n");
writeFileSync("src/lib/pdf-fonts.ts", `// GENERATED by scripts/make-pdf-fonts.mjs. Inter Tight and JetBrains Mono (SIL Open Font License). Do not edit.\nexport const PDF_FONTS = {\n${body}\n} as const;\n`);
console.log("wrote src/lib/pdf-fonts.ts");
